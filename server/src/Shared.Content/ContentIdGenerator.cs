using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using Realmforge.Rules.Definitions;

namespace Realmforge.Content
{
    /// <summary>Generates compile-time id constants so code that references specific content fails to build when it is renamed.</summary>
    public static class ContentIdGenerator
    {
        public static string Generate(ContentCatalog catalog)
        {
            var groups = new List<KeyValuePair<string, IEnumerable<string>>>
            {
                Group("Races", catalog.Races.Keys),
                Group("Classes", catalog.Classes.Keys),
                Group("Abilities", catalog.Abilities.Keys),
                Group("Perks", catalog.Perks.Keys),
                Group("Items", catalog.Items.Keys),
                Group("Continents", catalog.Continents.Keys),
                Group("Zones", catalog.Zones.Keys),
                Group("Mobs", catalog.Mobs.Keys),
                Group("Instances", catalog.Instances.Keys),
                Group("Npcs", catalog.Npcs.Keys),
                Group("Factions", catalog.Factions.Keys),
                Group("Quests", catalog.Quests.Keys),
                Group("Professions", catalog.Professions.Keys),
                Group("Cosmetics", catalog.Cosmetics.Keys),
                Group("StoreSkus", catalog.StoreSkus.Keys),
            };
            var builder = new StringBuilder();
            builder.AppendLine("// <auto-generated> by tools/ContentTool codegen. Do not edit by hand. </auto-generated>");
            builder.AppendLine("namespace Realmforge.Content.Generated");
            builder.AppendLine("{");
            builder.AppendLine("    public static class ContentIds");
            builder.AppendLine("    {");
            builder.AppendLine("        public const string Version = \"" + catalog.Version + "\";");
            foreach (KeyValuePair<string, IEnumerable<string>> group in groups)
            {
                builder.AppendLine();
                builder.AppendLine("        public static class " + group.Key);
                builder.AppendLine("        {");
                foreach (string id in group.Value.OrderBy(id => id, System.StringComparer.Ordinal))
                {
                    builder.AppendLine("            public const string " + ToIdentifier(id) + " = \"" + id + "\";");
                }
                builder.AppendLine("        }");
            }
            builder.AppendLine("    }");
            builder.AppendLine("}");
            return builder.ToString();
        }

        public static string ToIdentifier(string id)
        {
            var builder = new StringBuilder();
            foreach (string part in id.Split('_', '-', '.', ' ').Where(part => part.Length > 0))
            {
                builder.Append(char.ToUpper(part[0], CultureInfo.InvariantCulture));
                builder.Append(part.Substring(1));
            }
            string identifier = builder.ToString();
            return identifier.Length > 0 && char.IsDigit(identifier[0]) ? "_" + identifier : identifier;
        }

        private static KeyValuePair<string, IEnumerable<string>> Group(string name, IEnumerable<string> ids)
        {
            return new KeyValuePair<string, IEnumerable<string>>(name, ids);
        }
    }
}
